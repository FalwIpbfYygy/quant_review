def _tokenize(text: str) -> list:
    """中英文混合简单分词：英文按空格/标点；中文按字 + 二元串"""
    if not text:
        return []
    text = text.lower()
    tokens = []
    # 英文/数字 token
    en_tokens = re.findall(r"[a-z0-9]+", text)
    tokens.extend(en_tokens)
    # 中文：单字 + 二元邻接（提升中文检索）
    zh_chars = re.findall(r"[\u4e00-\u9fff]+", text)
    for seg in zh_chars:
        tokens.extend(list(seg))           # 单字
        if len(seg) >= 2:
            tokens.extend([seg[i:i + 2] for i in range(len(seg) - 1)])  # 二元串
    return tokens


def _build_index(kb: list):
    """为每个模块的每个 rule 建索引；返回 (rule_docs, rule_df, total_rules, avg_dl)"""
    rule_docs = []   # list[(module, rule, tf_counter, dl)]
    rule_df = Counter()
    total_len = 0
    for mod in kb:
        for rule in mod.rules:
            # 正文（决定文档长度 dl，用于长度归一化）
            base_text = " ".join([rule.name, rule.detail] + (rule.conditions or []))
            base_toks = _tokenize(base_text)
            # 加权词（只加词频 tf，不计入 dl）：标题 ×3、关键词 ×2
            boost_text = " ".join([rule.name] * 3 + list(rule.keywords or []) * 2)
            boost_toks = _tokenize(boost_text)
            tf = Counter(base_toks + boost_toks)
            dl = len(base_toks)
            rule_docs.append((mod, rule, tf, dl))
            total_len += dl
            for t in set(base_toks):   # df 只按正文统计，避免加权项抬高 df 压低 idf
                rule_df[t] += 1
    avg_dl = total_len / max(len(rule_docs), 1)
    return rule_docs, rule_df, avg_dl


_INDEX = _build_index(KB)
_RULE_DOCS, _RULE_DF, _AVG_DL = _INDEX


def search(query: str, top_k: int = 6, k1: float = 1.5, b: float = 0.75) -> list:
    """
    BM25 检索：返回 [(module, rule, score), ...]
    完全可审计：相同输入→相同输出，无随机/向量黑盒。
    """
    q_tokens = _tokenize(query)
    if not q_tokens:
        return []
    scores = []
    N = len(_RULE_DOCS)
    for mod, rule, tf, dl in _RULE_DOCS:
        if dl == 0:
            continue
        s = 0.0
        for qt in q_tokens:
            c = tf.get(qt, 0)
            if not c:
                continue
            df = _RULE_DF.get(qt, 0)
            idf = math.log(1 + (N - df + 0.5) / (df + 0.5))
            denom = c + k1 * (1 - b + b * dl / _AVG_DL)
            s += idf * (c * (k1 + 1)) / denom
        if s > 0:
            scores.append((mod, rule, s))
    scores.sort(key=lambda x: x[2], reverse=True)
    return scores[:top_k]


