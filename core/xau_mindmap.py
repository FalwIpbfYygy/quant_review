def list_modules() -> list:
    return [{"mid": m.mid, "title": m.title, "summary": m.summary,
             "source": m.source, "rule_count": len(m.rules)} for m in KB]


def get_module(mid: str) -> dict:
    for m in KB:
        if m.mid == mid:
            return {
                "mid": m.mid, "title": m.title, "summary": m.summary,
                "source": m.source,
                "rules": [asdict(r) for r in m.rules],
            }
    return {}


